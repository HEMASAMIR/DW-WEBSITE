const ORDER = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

/** Tone for a level code; unknown codes cycle through the palette by index. */
export function toneFor(code, index = 0) {
  const key = String(code || '').toUpperCase();
  return LEVEL_TONES[key] || LEVEL_TONES[ORDER[index % ORDER.length]];
}
